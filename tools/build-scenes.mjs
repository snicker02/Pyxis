// Build Pyxis's presets (formula/scenes.js).
//   node tools/build-scenes.mjs                 → rewrites formula/scenes.js from tools/scenes-list.json
//   node tools/build-scenes.mjs --scan <f.fract>…  → JSON summary of what the importer makes of each file
//
// Originals are written as overrides on top of the chosen formula's defaults.
// Mandelbulber scenes go through the app's own importer (the same code as the
// "Import Mandelbulber Settings" button), reading presets/mandelbulber/*.fract.
//
// Picking a preset resets every formula control (formula.presetReset), so a
// scene stores formula values only where they differ from the defaults. The
// camera, light and look are not reset by the engine, so every scene carries
// the STAGE keys in full; switching presets then always gives the same picture.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import '../formula/index.js';
import { defaults } from '../formula/params.js';
import { VARIANT_DEFAULTS } from '../formula/presets.js';
import { importMandelbulber } from '../core/engine/mbimport.js';

const here = p => fileURLToPath(new URL(p, import.meta.url));
const D = defaults();
const STAGE = ['rotX', 'rotY', 'dist', 'targetX', 'targetY', 'targetZ', 'lens', 'rollX', 'rollY', 'rollZ', 'deepZoom',
  'objX', 'objY', 'objZ', 'objRotX', 'objRotY', 'objRotZ', 'objScale',
  'palette', 'colorShift', 'brightness', 'tonemap', 'vignette', 'bgColor', 'lightColor', 'ambient', 'fog', 'volumetric',
  'aoStrength', 'stepAO', 'shadows', 'shadowSoft', 'dofStrength', 'focalDist', 'envMode', 'groundType', 'renderMode',
  'lightX', 'lightY', 'lightZ', 'lightRelative', 'light2On', 'light3On'].filter(k => k in D);
const num = x => typeof x === 'number' ? +x.toPrecision(12) : x;
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const sceneValues = full => {
  const v = {};
  for (const [k, x] of Object.entries(full)) if (k in D && (STAGE.includes(k) || !same(D[k], x))) v[k] = num(x);
  return v;
};

const args = process.argv.slice(2);
if (args[0] === '--scan') {
  const out = [];
  for (const f of args.slice(1)) {
    const r = importMandelbulber(readFileSync(f, 'utf8'));
    out.push({ file: f, ok: r.ok, formula: r.formula, error: r.error, notes: r.notes, v: r.ok ? sceneValues({ ...D, ...r.params }) : null });
  }
  console.log(JSON.stringify(out));
} else {
  const list = JSON.parse(readFileSync(here('./scenes-list.json'), 'utf8'));
  const lines = [];
  for (const o of list.originals) {
    const full = { ...D, ...VARIANT_DEFAULTS[o.variant], ...list.look, ...o.v };
    const credit = o.credit ? `, credit: ${JSON.stringify(o.credit)}` : '';
    lines.push(`  ${o.key}: { group: '${o.group || 'pyxis'}', label: ${JSON.stringify(o.label)}${credit}, v: ${JSON.stringify(sceneValues(full))} },`);
  }
  for (const it of list.fract) {
    const r = importMandelbulber(readFileSync(here(`../presets/mandelbulber/${it.file}`), 'utf8'));
    if (!r.ok) throw new Error(`${it.file}: ${r.error}`);
    const credit = list.groups.find(g => g[1] === it.group)[0].replace(/ \(CC-BY 4\.0\)$/, '');
    lines.push(`  ${it.key}: { group: '${it.group}', label: ${JSON.stringify(it.label)}, credit: ${JSON.stringify(`${credit} · ${it.file} · CC-BY 4.0`)}, v: ${JSON.stringify(sceneValues({ ...D, ...r.params, ...(it.tweak || {}) }))} },`);
  }
  const src = `// Pyxis's preset scenes. GENERATED by tools/build-scenes.mjs from
// tools/scenes-list.json — edit that list and re-run, don't edit this file.
// Mandelbulber scenes: presets/mandelbulber/*.fract, CC-BY 4.0, credited per scene.
export const PRESET_GROUPS = ${JSON.stringify(list.groups)};
export const SCENES = {
${lines.join('\n')}
};
`;
  writeFileSync(here('../formula/scenes.js'), src);
  console.log(`formula/scenes.js: ${lines.length} scenes`);
}
